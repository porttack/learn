#!/usr/bin/env python3
"""Write the MATE and Ocean Decade views of the skills widget into the porttack.com data file.

The shared widget (porttack.com assets/skills-widget.js and skills-widget-data.js) draws the "Skills <-> Standards"
chart. This script generates every view that involves MATE's 18 skills or the UN Ocean Decade's ten challenges from
this repo's JSON, and writes it between two marker comments in skills-widget-data.js, so it can be re-run:

    // BEGIN MATE AND OCEAN VIEWS ...   ...   // END MATE AND OCEAN VIEWS

Views: mate25, mate30, ocean (bars), ocean-mate, wef30-ocean, ocean-wef30. Then run tools/sync_skills_widget.sh to
copy the widget here and tools/check_mate_wef_sync.mjs to confirm the two agree.

Usage: build_skills_widget_data.py [path-to-skills-widget-data.js]   (default ../porttack.com/assets/skills-widget-data.js)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S = ROOT / "_standards"
BEGIN = "  // BEGIN MATE AND OCEAN VIEWS (generated by learn.porttack.com/tools/build_skills_widget_data.py; edit the JSON there, not this block)"
END = "  // END MATE AND OCEAN VIEWS"


def load(name):
    return json.loads((S / name).read_text(encoding="utf-8"))


def J(x):
    return json.dumps(x, ensure_ascii=False)


skills = load("mate-skills.json")
comps = load("mate-rov.json")
wef = load("mate-wef-links.json")
ocean = load("mate-ocean-links.json")
od_cat = load("ocean-decade.json")
missions = load("carriers/mate-missions.json")

WEF25 = [w["index"] for w in sorted((w for w in wef["wef_skills"] if w["rank_2025"]), key=lambda w: w["rank_2025"])]
WEF30 = [w["index"] for w in sorted((w for w in wef["wef_skills"] if w["rank_2030"]), key=lambda w: w["rank_2030"])]
challenges = [i for g in od_cat["groups"] if g["code"] == "OD" for i in g["items"]]
od_index = {c["code"]: n for n, c in enumerate(challenges)}
users = {}
for g in comps["groups"]:
    for i in g["items"]:
        for sk in i.get("skills", []):
            users.setdefault(sk, []).append((i["code"], i["name"]))
tasks = missions["meta"]["locator_titles"]
od_tasks = {code: [k for k in e["locators"] if k != "2026-0"] for code, e in missions["coverage"]["ocean-decade"].items()}

out = [BEGIN]

# ---- MATE's 18 skills as the right-hand anchors, with the competencies that develop each ----
anch, det = [], []
for g in skills["groups"]:
    cls = "human" if g["code"] == "GEN" else "tech"
    for i in g["items"]:
        anch.append("    {id:%s, disp:%s, name:%s, cls:%s, unit:\"skill\"}" % (J(i["code"]), J(i["code"]), J(i["name"]), J(cls)))
        subs = ",\n        ".join("{n:%s, t:%s}" % (J(c), J(n)) for c, n in users.get(i["code"], []))
        det.append("    %s: {desc:%s, subs:[\n        %s\n    ]}" % (J(i["code"]), J(i["paraphrase"]), subs))
out.append("  // MATE's 18 skills (Evaluate-Compete). The employer-skill links are authored in learn.porttack.com/_standards/mate-wef-links.json.")
out.append("  var MATE_ANCHORS = [\n" + ",\n".join(anch) + "\n  ];")
out.append("  var MATE_LINKS = [\n    " + ",\n    ".join("{s:%d, a:%s, w:%s}" % (l["s"], J(l["a"]), J(l["w"])) for l in wef["links"]) + "\n  ];")
out.append("  var MATE_DETAILS = {\n" + ",\n".join(det) + "\n  };")

# ---- Ocean 10: the left list, the right anchors, the bars ----
out.append("  // The Ocean Decade's ten challenges (oceandecade.org), as a left list, as right-hand anchors and as bars.")
out.append("  var OCEAN_LEFT = [\n" + ",\n".join("    {name:%s, cls:\"ocean\"}" % J(f"{n + 1}. {c['name']}") for n, c in enumerate(challenges)) + "\n  ];")
oa, od_det = [], []
for n, c in enumerate(challenges):
    oa.append("    {id:%s, disp:%s, name:%s, cls:\"ocean\", unit:\"challenge\"}" % (J(c["code"]), J(str(n + 1)), J(c["name"])))
    subs = ",\n        ".join("{n:%s, t:%s}" % (J(k), J(tasks[k].split(": ", 1)[-1])) for k in od_tasks.get(c["code"], []))
    od_det.append("    %s: {desc:%s, subs:[\n        %s\n    ]}" % (J(c["code"]), J(c["paraphrase"] + (" MATE tags it on these mission tasks:" if od_tasks.get(c["code"]) else " MATE did not tag it on any mission task in the manuals read.")), subs))
out.append("  var OCEAN_ANCHORS = [\n" + ",\n".join(oa) + "\n  ];")
out.append("  var OCEAN_DETAILS = {\n" + ",\n".join(od_det) + "\n  };")
bars = []
for c in challenges:
    k = len(od_tasks.get(c["code"], []))
    bars.append("    {name:%s, cls:\"ocean\", w:100, valText:%s}" % (J(c["name"]), J(str(k))))
out.append("  // Equal-length bars: the challenges are not ranked. The value is how many of MATE's mission tasks (2024 to 2026) tag the challenge (a plain number; the caption says what it counts).")
out.append("  var OCEAN_BARS = [\n" + ",\n".join(bars) + "\n  ];")

# ---- The 2030 skills as right-hand anchors (for the Ocean 10 to 2030 view) ----
wa, wd = [], []
rank30 = {w["index"]: w for w in wef["wef_skills"]}
for idx in WEF30:
    w = rank30[idx]
    wa.append("    {id:%s, disp:%s, name:%s, cls:%s_CLS[%d], unit:\"skill\"}" % (J(f"w{idx}"), J(str(w["rank_2030"])), J(w["name"]), "CTE", idx))
    r25 = f"Ranked {w['rank_2025']} of ten most essential in 2025." if w["rank_2025"] else "Not on the 2025 most essential list."
    wd.append("    %s: {desc:%s, subs:[]}" % (J(f"w{idx}"), J(f"Ranked {w['rank_2030']} of ten skills growing fastest to 2030. {r25}")))
out.append("  var WEF30_CLS = CTE.map(function (d) { return d.cls; });".replace("WEF30_CLS", "CTE_CLS"))
out.append("  var WEF30_ANCHORS = [\n" + ",\n".join(wa) + "\n  ];")
out.append("  var WEF30_DETAILS = {\n" + ",\n".join(wd) + "\n  };")

# ---- helpers and the six views ----
out.append("""  var WEF25_IDX = %s;
  var WEF30_IDX = %s;
  function pick(idxs) { return idxs.map(function (i) { return {name: CTE[i].name, cls: CTE[i].cls}; }); }
  function remap(links, idxs) {
    var out = [];
    links.forEach(function (l) { var p = idxs.indexOf(l.s); if (p !== -1) out.push({s: p, a: l.a, w: l.w}); });
    return out;
  }""" % (J(WEF25), J(WEF30)))
out.append("  var WEF30_OCEAN_LINKS = [\n    " + ",\n    ".join("{s:%d, a:%s, w:%s}" % (l["s"], J(l["a"]), J(l["w"])) for l in ocean["wef30_ocean"]) + "\n  ]; // s = index in CTE")
out.append("  var OCEAN_MATE_LINKS = [\n    " + ",\n    ".join("{s:%d, a:%s, w:%s}" % (od_index[l["o"]], J(l["a"]), J(l["w"])) for l in ocean["ocean_mate"]) + "\n  ]; // s = index in OCEAN_LEFT")

hint_challenge = "Hover or tap a challenge on the left to light up its matches, or an item on the right to read its full text."
hint_skill = "Hover or tap a skill on the left to light up its matches, or an item on the right to read its full text."
out.append("""  var MATE_OCEAN = {
    matchViews: {
      mate25: {left: pick(WEF25_IDX), leftTitle: "WEF skills, 2025 most essential", leftNoun: "employer skills", anchors: MATE_ANCHORS, links: remap(MATE_LINKS, WEF25_IDX), details: MATE_DETAILS, covered: {}, rightTitle: "MATE ROV skills (Evaluate-Compete)", hint: %s},
      mate30: {left: pick(WEF30_IDX), leftTitle: "WEF skills, growing fastest to 2030", leftNoun: "employer skills", anchors: MATE_ANCHORS, links: remap(MATE_LINKS, WEF30_IDX), details: MATE_DETAILS, covered: {}, rightTitle: "MATE ROV skills (Evaluate-Compete)", hint: %s},
      "ocean-mate": {left: OCEAN_LEFT, leftTitle: "Ocean Decade challenges", leftNoun: "Ocean Decade challenges", anchors: MATE_ANCHORS, links: OCEAN_MATE_LINKS, details: MATE_DETAILS, covered: {}, rightTitle: "MATE ROV skills (Evaluate-Compete)", hint: %s},
      "wef30-ocean": {left: pick(WEF30_IDX), leftTitle: "WEF skills, growing fastest to 2030", leftNoun: "employer skills", anchors: OCEAN_ANCHORS, links: remap(WEF30_OCEAN_LINKS, WEF30_IDX), details: OCEAN_DETAILS, covered: {}, rightTitle: "Ocean Decade challenges", hint: %s},
      "ocean-wef30": {left: OCEAN_LEFT, leftTitle: "Ocean Decade challenges", leftNoun: "Ocean Decade challenges", anchors: WEF30_ANCHORS, links: [], details: WEF30_DETAILS, covered: {}, rightTitle: "WEF skills, growing fastest to 2030", hint: %s}
    },
    bars: {ocean: OCEAN_BARS},
    captions: {}
  };
  // The same links read from the other side: challenge on the left, 2030 skill (anchor "w<index>") on the right.
  MATE_OCEAN.matchViews["ocean-wef30"].links = WEF30_OCEAN_LINKS.map(function (l) { return {s: parseInt(l.a.slice(3), 10) - 1, a: "w" + l.s, w: l.w}; });""" % (J(hint_skill), J(hint_skill), J(hint_challenge), J(hint_skill), J(hint_challenge)))

# ---- captions (plain words; the claims are computed so they stay true) ----
def uncovered(links_by_view, names):
    return [n for n in names if n not in links_by_view]
mate_names = {i["code"]: i["name"] for g in skills["groups"] for i in g["items"]}
def mate_gaps(idxs):
    linked = {l["a"] for l in wef["links"] if l["s"] in idxs}
    return [mate_names[c] for c in mate_names if c not in linked]
def listed(xs):
    return xs[0] if len(xs) == 1 else ", ".join(xs[:-1]) + " and " + xs[-1]
g25, g30 = mate_gaps(WEF25), mate_gaps(WEF30)
solid_ocean = {l["a"] for l in ocean["ocean_mate"]}
no_ocean = [mate_names[c] for c in mate_names if c not in {l["a"] for l in ocean["ocean_mate"]}]
only_dashed = [f"challenge {od_index[c] + 1}" for c in od_index if all(l["w"] == "partial" for l in ocean["wef30_ocean"] if l["a"] == c)]
tag_none = [str(od_index[c] + 1) for c in od_index if not od_tasks.get(c)]
caps = {
 "mate25": "<b>The ten skills employers called most essential in 2025, against MATE's eighteen.</b> Solid lines are direct matches, dashed lines partial ones. %s match none of these ten." % listed(g25),
 "mate30": "<b>The ten skills growing fastest to 2030, against MATE's eighteen.</b> Solid lines are direct matches, dashed lines partial ones. %s match none of these ten. Empathy and service orientation were on the 2025 list but are not on the 2030 one, which is why Communication, Entrepreneurship and Technical Presentation lose their lines." % listed(g30),
 "ocean": "<b>The ten Ocean Decade challenges.</b> The bars are all the same length because the challenges are not ranked. The number on the right is how many of MATE's mission tasks from 2024 to 2026 tag each one. MATE tagged no task with challenges %s." % listed(tag_none),
 "ocean-mate": "<b>The ten Ocean Decade challenges, against MATE's eighteen skills.</b> MATE tags mission tasks, not skills, so a solid line follows MATE's own tags through the competencies that develop each skill, and a dashed line is this project's reading. Technology and Society and Project Knowledge and Skills carry most of the solid lines because every understanding competency lists them. %s have no line." % listed(no_ocean),
 "wef30-ocean": "<b>The ten skills growing fastest to 2030, against the ten Ocean Decade challenges.</b> Neither source links the two, so every line is this project's reading: solid where the challenge is mainly that skill, dashed where the skill is a real piece of it. Every challenge has a line; %s has only a dashed one." % listed(only_dashed),
 "ocean-wef30": "<b>The same links, read from the Ocean Decade side.</b> Pick a challenge on the left to see which of the 2030 skills it calls for. Solid lines mean the challenge is mainly that skill; dashed lines mean the skill is a real piece of it.",
}
out.append("  MATE_OCEAN.captions = " + json.dumps(caps, ensure_ascii=False, indent=4).replace("\n", "\n  ") + ";")
out.append(END)
block = "\n".join(out) + "\n"

path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT.parent / "porttack.com" / "assets" / "skills-widget-data.js"
src = path.read_text(encoding="utf-8")
if BEGIN in src and END in src:
    a, b = src.index(BEGIN), src.index(END) + len(END) + 1
    src = src[:a] + block + src[b:]
else:
    # first run: replace the earlier hand-inserted MATE block
    a = src.index("  // ---- MATE ROV Competition match-up (hidden view \"mate\")")
    b = src.index("  // Everything a match-up view needs, keyed by view name.\n")
    src = src[:a] + block + "\n" + src[b:]
path.write_text(src, encoding="utf-8")
print(f"wrote {len(block.splitlines())} lines to {path}")
