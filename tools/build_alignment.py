def esc(s):
    return htmlmod.escape(s, quote=False) if s else ""


CHAP_REF_RE = re.compile(r"\bchap(\d{2})([a-z]?)\b")


def humanize_chapter_refs(text, interlude_letters=None):
    """Carrier notes are written by/for editors, who naturally use the book's own
    internal shorthand ("chap07", "chap07b") -- the same convention used throughout
    AUDIT.md and CHAPTER_MANIFEST.md. That shorthand means nothing to a reader of a
    published standards page, so displayed notes spell it out: "chap07" -> "Chapter 7",
    or "chap07b" -> "Interlude B" when that locator has an assigned interlude letter
    (matching how the carrier link itself displays it -- see _locator_clause).
    Applied at render time, not by editing the source notes, so authors can keep
    writing new notes the way they always have."""
    interlude_letters = interlude_letters or {}

    def repl(m):
        key = f"{int(m.group(1))}{m.group(2)}"
        if key in interlude_letters:
            return f"Interlude {interlude_letters[key]}"
        return f"Chapter {key}"

    return CHAP_REF_RE.sub(repl, text)


def load_json(path):
    return json.loads(Path(path).read_text())


class Coverage:
    """Joins catalog codes against loaded carrier files for one framework."""

    def __init__(self, carrier_files, framework, scoped):
        self.by_code = {}
        self.scoped = scoped
        self.source_meta = {source: data.get("meta", {}) for source, data in carrier_files.items()}
        for source, data in carrier_files.items():
            for code, entry in data.get("coverage", {}).get(framework, {}).items():
                self.by_code.setdefault(code, []).append((source, entry))

    def get(self, code):
        return self.by_code.get(code, [])

    def _locator_url(self, source, locator, anchor_slug):
        """Resolve a locator to a URL, or None if its source has no url template
        (little_brother, supplement -- nowhere to link yet). The ?readonly suffix is
        specific to working_in_python's JupyterLite setup -- it always links to the
        static read-only view (no live pane) rather than the interactive notebook,
        since a chapter's live pane can interfere with anchor scrolling and a reader
        clicking through from a standards page wants to read the content, not launch
        a kernel -- so it's opt-in via meta.readonly_suffix, not assumed for every
        source with a locator_url_template. A plain single-page source (a blog post,
        say) just wants its own URL back, with no notebook-specific query string
        tacked onto the end."""
        meta = self.source_meta.get(source, {})
        template = meta.get("locator_url_template")
        if not template:
            return None
        # Chapter locators zero-pad only the leading numeric run, e.g. 3 -> "03" and
        # the lettered interlude "7b" -> "07b" (never "7b" padded to width 2, which
        # would wrongly leave it unpadded since it's already 2 characters long).
        # locator_slugs overrides this entirely for a source whose real per-locator
        # URL isn't a zero-padded number (e.g. Jekyll's full-filename permalinks, or
        # a non-chapter source whose locators don't share one predictable path shape
        # at all -- cs50psets' Readability locator is a full external-looking path,
        # not even under its own pathway's usual prefix) -- opt-in per locator, checked
        # regardless of locator_kind, so every source/locator without an entry behaves
        # exactly as before.
        slug = meta.get("locator_slugs", {}).get(str(locator))
        if slug:
            padded = slug
        elif meta.get("locator_kind") == "chapter":
            m = re.match(r"^(\d+)([a-zA-Z]*)$", str(locator))
            padded = f"{int(m.group(1)):02d}{m.group(2)}" if m else str(locator)
        else:
            padded = str(locator)
        url = template.format(base_url=meta.get("base_url", ""), locator=padded)
        if meta.get("readonly_suffix"):
            url += f"?readonly#{anchor_slug}" if anchor_slug else "?readonly"
        elif anchor_slug:
            url += f"#{anchor_slug}"
        return url

    def _locator_clause(self, source, locator, anchor):
        """"Chapter 9 (Lists)", or with a known section instead, "Chapter 4 – Defining
        new functions" -- the section title (specific to this standard) takes priority
        over the chapter's own title (generic, the same for every standard in that
        chapter) when both are known. A locator with an assigned interlude letter (an
        editorial label, e.g. "6b" -> "A") reads as "Interlude A" instead of "Chapter
        6b" -- display only, the URL still resolves from the underlying locator, since
        this is not a file/URL rename. locator_kind "none" (a source with no real
        sub-units, e.g. a single blog post) skips the "Chapter"/"Unit" noun entirely
        and just shows that locator's own title -- "Unit post" would imply structure
        that doesn't exist. Linked when the source has somewhere to link to, plain
        text otherwise."""
        meta = self.source_meta.get(source, {})
        interlude_letter = meta.get("interlude_letters", {}).get(str(locator))
        locator_title = meta.get("locator_titles", {}).get(str(locator))
        if interlude_letter:
            text = f"Interlude {interlude_letter}"
        elif meta.get("locator_kind") in ("none", "activity"):
            text = locator_title or "the source"
        else:
            noun = "Chapter" if meta.get("locator_kind") == "chapter" else "Unit"
            text = f"{noun} {locator}"
        section_title = anchor.get("title") if anchor else None
        if section_title:
            text += f" – {section_title}"
        elif locator_title and meta.get("locator_kind") not in ("none", "activity"):
            text += f" ({locator_title})"
        url = self._locator_url(source, locator, anchor.get("slug") if anchor else None)
        return f'<a href="{esc(url)}">{esc(text)}</a>' if url else esc(text)

    def _carrier_clause(self, source, entry, with_title):
        """One source's coverage of one code, as plain body text (no wrapping
        element -- callers decide whether that's a <li> or the only sentence in
        a <p>). with_title=False drops the leading source name, for scoped
        (single-source) mode where it would just repeat the one source this
        run was given on every line."""
        locs = entry.get("locators", [])
        anchors = entry.get("anchors", {})
        title = esc(self.source_meta.get(source, {}).get("title", source))
        if locs:
            clauses = ", ".join(self._locator_clause(source, loc, anchors.get(str(loc))) for loc in locs)
            strength = entry.get("strength")
            if strength and strength != "strong":
                clauses += f' <span class="meta-strength">({esc(strength)})</span>'
            return f"Covered in {clauses}" if not with_title else f"<strong>{title}:</strong> {clauses}"
        if entry.get("checked"):
            return "Not covered" if not with_title else f"<strong>{title}:</strong> not covered"
        return "Covered, no locator on record" if not with_title else f"<strong>{title}:</strong> covered, no locator on record"

    def carrier_html(self, code):
        """None means: say nothing (used when --source scoping is active and this
        code has no coverage from the loaded source -- it may well be carried by a
        source this run was never given, and "unassigned" would be a false claim of
        a gap. Only the unscoped, all-sources view may claim "Unassigned". Returns
        a complete, ready-to-insert HTML block -- callers must NOT esc() the result
        and must NOT wrap it in another element (scoped mode returns its own <p
        class="meta">; the cross-source view, where a popular code can easily be
        carried by half a dozen sources, returns a <ul class="meta-list"> with one
        line per source instead of the old single run-on sentence, which became
        unreadable once several sources piled into it)."""
        entries = self.get(code)
        if not entries:
            return None if self.scoped else '<p class="meta">Unassigned</p>'
        if self.scoped:
            # A scoped run only ever loads one carrier file, so there's at most
            # one entry here -- a single sentence reads fine, no list needed.
            parts = [self._carrier_clause(source, entry, with_title=False) for source, entry in entries]
            return f'<p class="meta">{"; ".join(parts)}</p>'
        # Each source's own note is folded into its own <li> here, right under
        # that source's "Covered by" line -- a flat list of notes rendered
        # separately below (the old behavior, still used in scoped mode) has no
        # way to show which note belongs to which source once there's more than
        # one, which is exactly the confusing part a reader flagged.
        items = []
        for source, entry in entries:
            li = self._carrier_clause(source, entry, with_title=True)
            if entry.get("note"):
                note = esc(humanize_chapter_refs(entry["note"], self.source_meta.get(source, {}).get("interlude_letters")))
                li += f'<div class="meta-note">{note}</div>'
            items.append(f"<li>{li}</li>")
        return f'<ul class="meta-list">{"".join(items)}</ul>'

    def coverage_summary(self, code):
        """(covering: list[str], total: int) -- of every source this Coverage was
        built from (self.source_meta), which ones actually cover `code`. Same
        covered/not-covered predicate carrier_html already applies: an entry counts
        as covering unless it's checked=true with empty locators (an explicit
        acknowledged gap, not silence)."""
        covering = [source for source, entry in self.get(code) if not (entry.get("checked") and not entry.get("locators"))]
        return covering, len(self.source_meta)

    def notes(self, code):
        """Only meaningful in scoped (single-source) mode. The cross-source view
        folds each source's note directly into its own <li> in carrier_html()
        instead -- see the comment there -- so this returns nothing there, and
        callers' existing "for note in cov.notes(code)" loops naturally render
        nothing extra rather than showing every note twice."""
        if not self.scoped:
            return []
        return [
            humanize_chapter_refs(entry["note"], self.source_meta.get(source, {}).get("interlude_letters"))
            for source, entry in self.get(code)
            if entry.get("note")
        ]


def load_carrier_files(carriers_dir, sources):
    files = {}
    for path in sorted(Path(carriers_dir).glob("*.json")):
        data = load_json(path)
        source = data["meta"]["source"]
        if sources and source not in sources:
            continue
        files[source] = data
    return files


