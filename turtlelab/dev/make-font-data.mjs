// Dev tool, not part of the app. Writes js/ui/roboto-data.js: the Roboto font file, as text
// the page's own code can use. The PDF needs the font inside a picture of the blocks (see
// js/ui/code-image.js), and the font is built into the code, not fetched, so making a PDF
// uses no network at all. Run it again if fonts/roboto/Roboto-Regular.woff2 ever changes:
//   node turtlelab/dev/make-font-data.mjs
// A test fails if the two do not match.
// Copyright (C) 2026 Eric Brown. Licensed under the GNU AGPL-3.0 or later.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);

export function fontModule() {
  const base64 = readFileSync(new URL('fonts/roboto/Roboto-Regular.woff2', root)).toString('base64');
  return `// TurtleLab: the Roboto font, as text. GENERATED by dev/make-font-data.mjs from
// fonts/roboto/Roboto-Regular.woff2: do not edit it, run that script again.
// Roboto is licensed under the Apache License 2.0 (see fonts/roboto/LICENSE-Apache-2.0.txt).
// It is here so the PDF can draw blocks with the right font without fetching anything.

export const ROBOTO_REGULAR_BASE64 =
  '${base64}';
`;
}

if (process.argv[1] && new URL(`file://${process.argv[1]}`).href === import.meta.url) {
  writeFileSync(new URL('js/ui/roboto-data.js', root), fontModule());
  console.log('wrote js/ui/roboto-data.js');
}
